#!/usr/bin/env node
/* build-strokes.js — games/strokes.json (the one source of truth) → games/strokes.js
   so games/write.html also works from file:// (fetch() of a local JSON is blocked there).
   Also lints the data: every stroke's "start" must equal the first point of its path.
   Run from anywhere:  node games/build-strokes.js                                     */
'use strict';
var fs = require('fs'), path = require('path');
var src = path.join(__dirname, 'strokes.json'), out = path.join(__dirname, 'strokes.js');
var data = JSON.parse(fs.readFileSync(src, 'utf8'));
var problems = [], n = 0;
data.levels.forEach(function (lv) {
  lv.items.forEach(function (it) {
    it.strokes.forEach(function (s, i) {
      n++;
      var m = /^M\s*(-?[\d.]+)[\s,]+(-?[\d.]+)/.exec(s.d);
      if (!m) problems.push(it.id + '#' + (i + 1) + ': path must start with M x y');
      else if (!s.start || +m[1] !== s.start[0] || +m[2] !== s.start[1]) problems.push(it.id + '#' + (i + 1) + ': start ' + JSON.stringify(s.start) + ' ≠ M ' + m[1] + ' ' + m[2]);
      ['kind', 'dir', 'say', 'en'].forEach(function (k) { if (!s[k]) problems.push(it.id + '#' + (i + 1) + ': missing ' + k); });
    });
  });
});
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
fs.writeFileSync(out, '/* generated by games/build-strokes.js from games/strokes.json — do not edit by hand */\nwindow.STROKES = ' + JSON.stringify(data) + ';\n');
console.log('strokes.js: ' + data.levels.reduce(function (a, l) { return a + l.items.length; }, 0) + ' items, ' + n + ' strokes, 0 problems');
